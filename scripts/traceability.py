#!/usr/bin/env python3
"""Generate docs/traceability.md from the policies' own METADATA annotations.

The control -> policy -> test matrix is derived from the code, never typed by
hand, so it cannot drift from what is actually enforced. CI runs this with
--check and fails if the committed matrix is stale.

Usage:
    scripts/traceability.py            # rewrite docs/traceability.md
    scripts/traceability.py --check    # exit 1 if it would change
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "traceability.md"
OPA = "opa"


def rule_annotations():
    raw = subprocess.run(
        [OPA, "inspect", "-a", "--format", "json", str(ROOT / "policy")],
        check=True, capture_output=True, text=True,
    ).stdout
    rows = {}
    for entry in json.loads(raw).get("annotations", []):
        ann = entry["annotations"]
        custom = ann.get("custom") or {}
        if ann.get("scope") != "rule" or "id" not in custom:
            continue
        path = [p["value"] for p in entry["path"][1:]]
        rows[custom["id"]] = {
            "id": custom["id"],
            "title": ann.get("title", "").split(" ", 1)[-1],
            "clause": custom.get("clause", ""),
            "severity": custom.get("severity", ""),
            "package": ".".join(path[:-1]),
            "kind": path[-1],
        }
    return rows


def tests_per_policy():
    counts = {}
    for f in (ROOT / "tests").glob("*_test.rego"):
        for name in re.findall(r"^test_(\w+) if", f.read_text(), re.M):
            m = re.match(r"(sdls|crypto|mission)_(\d{3})_", name)
            if m:
                pid = f"{m.group(1).upper()}-{m.group(2)}"
                counts[pid] = counts.get(pid, 0) + 1
    return counts


def render(rows, tests):
    def order(pid):
        prefix, num = pid.split("-")
        return (["SDLS", "CRYPTO", "MISSION"].index(prefix), int(num))

    lines = [
        "# Traceability matrix",
        "",
        "<!-- Generated by scripts/traceability.py from policy METADATA. Do not edit by hand. -->",
        "",
        "| Policy | Requirement | Source clause | Severity | Enforced as | Tests |",
        "|---|---|---|---|---|---|",
    ]
    for pid in sorted(rows, key=order):
        r = rows[pid]
        kind = "deny" if r["kind"] == "deny" else "warn"
        lines.append(
            f"| `{pid}` | {r['title']} | {r['clause']} | {r['severity']} | "
            f"`{r['package']}` ({kind}) | {tests.get(pid, 0)} |"
        )
    untested = [p for p in rows if tests.get(p, 0) == 0]
    lines += ["", f"{len(rows)} policies, {sum(tests.values())} policy-specific tests."]
    if untested:
        lines.append(f"Untested: {', '.join(sorted(untested))}.")
    return "\n".join(lines) + "\n", untested


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    text, untested = render(rule_annotations(), tests_per_policy())
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("docs/traceability.md is stale: run scripts/traceability.py", file=sys.stderr)
            return 1
        if untested:
            print(f"policies without tests: {untested}", file=sys.stderr)
            return 1
        print("traceability matrix up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
